const EXPORT_OPTIONS = [
  { id: 'csv',    icon: Table,    label: 'CSV Data',     desc: 'Raw dataset as comma-separated values',    color: 'from-emerald-600 to-teal-600' },
  { id: 'json',   icon: Code,     label: 'JSON Data',    desc: 'Dataset exported as structured JSON',       color: 'from-red-600 to-rose-600' },
  { id: 'report', icon: FileText, label: 'HTML Report',  desc: 'Full analysis report as HTML document',     color: 'from-amber-500 to-orange-500' },
  { id: 'stats',  icon: Table,    label: 'Stats CSV',    desc: 'Column statistics as downloadable CSV',     color: 'from-violet-600 to-purple-600' },
];

export default function ExportPanel({ rows, headers, summary, insights, recommendations, datasetName }: Props) {
  const [exported, setExported] = useState<string[]>([]);

  function doExport(id: string) {
    const base = datasetName.replace(/\.[^.]+$/, '');
    switch (id) {
      case 'csv':
        downloadBlob(rowsToCSV(rows, headers), `${base}_data.csv`, 'text/csv');
        break;
      case 'json':
        downloadBlob(JSON.stringify(rows, null, 2), `${base}_data.json`, 'application/json');
        break;
      case 'report': {
        const html = buildHTMLReport(summary, insights, recommendations, datasetName);
        downloadBlob(html, `${base}_report.html`, 'text/html');
        break;
      }
      case 'stats': {
        const statRows = summary.columns.map(c =>
          `${c.name},${c.type},${c.missing},${c.missingPct},${c.unique},${c.mean ?? ''},${c.std ?? ''},${c.min ?? ''},${c.max ?? ''},${c.skewness ?? ''}`
        );
        const csv = `Column,Type,Missing,Missing%,Unique,Mean,Std,Min,Max,Skewness\n${statRows.join('\n')}`;
        downloadBlob(csv, `${base}_statistics.csv`, 'text/csv');
        break;
      }
    }
    setExported(prev => [...prev, id]);
    setTimeout(() => setExported(prev => prev.filter(x => x !== id)), 3000);
  }

  return (
    <div className="space-y-5">
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
        {EXPORT_OPTIONS.map(({ id, icon: Icon, label, desc, color }) => (
          <GlowCard key={id} className="p-5 card-hover">
            <div className="flex items-start gap-3">
              <div className={`w-10 h-10 rounded-xl bg-gradient-to-br ${color} flex items-center justify-center flex-shrink-0`}>
                <Icon size={18} className="text-white" />
              </div>
              <div className="flex-1">
                <div className="text-sm font-semibold text-white mb-0.5">{label}</div>
                <div className="text-[11px] text-slate-500 mb-3">{desc}</div>
                <button
                  onClick={() => doExport(id)}
                  className={`flex items-center gap-1.5 px-4 py-2 rounded-lg text-xs font-semibold transition-all ${
                    exported.includes(id)
                      ? 'bg-emerald-500/10 border border-emerald-500/30 text-emerald-400'
                      : `bg-gradient-to-r ${color} text-white hover:opacity-90 btn-glow`
                  }`}
                >
                  {exported.includes(id) ? <><CheckCircle size={11} />Downloaded</> : <><Download size={11} />Download</>}
                </button>
              </div>
            </div>
          </GlowCard>
        ))}
      </div>

      {/* Summary of what's included */}
      <GlowCard className="p-5">
        <div className="text-xs font-semibold text-white mb-3">Report Contents</div>
        <div className="grid grid-cols-2 gap-2">
          {[
            `${summary.totalRows.toLocaleString()} data rows`,
            `${summary.totalCols} columns analysed`,
            `${summary.columns.length} column stat sheets`,
            `${insights.length} AI insights`,
            `${recommendations.length} ML recommendations`,
            'Correlation matrix data',
            'Health & AI scores',
            'Dataset metadata',
          ].map(item => (
            <div key={item} className="flex items-center gap-2 text-[11px] text-slate-400">
              <CheckCircle size={10} className="text-emerald-400 flex-shrink-0" />
              {item}
            </div>
          ))}
        </div>
      </GlowCard>
    </div>
  );
}
